pub fn lookup(name: &str) -> Option<(&'static str, Kind)> {
    if let Some(&(_, s)) = GREEK.iter().find(|(n, _)| *n == name) {
        return Some((s, Kind::Ord));
    }
    if let Some(&(_, s)) = UPPER_GREEK.iter().find(|(n, _)| *n == name) {
        return Some((s, Kind::Ord));
    }
    SYMBOLS.iter().find(|(n, _, _)| *n == name).map(|&(_, s, k)| (s, k))
}

pub fn is_greek_lower(s: &str) -> bool {
    GREEK.iter().any(|(_, g)| *g == s)
}

pub fn blackboard(c: char) -> char {
    match c {
        'C' => 'ℂ',
        'H' => 'ℍ',
        'N' => 'ℕ',
        'P' => 'ℙ',
        'Q' => 'ℚ',
        'R' => 'ℝ',
        'Z' => 'ℤ',
        'A'..='Z' => char::from_u32(0x1D538 + (c as u32 - 'A' as u32)).unwrap_or(c),
        'a'..='z' => char::from_u32(0x1D552 + (c as u32 - 'a' as u32)).unwrap_or(c),
        '0'..='9' => char::from_u32(0x1D7D8 + (c as u32 - '0' as u32)).unwrap_or(c),
        _ => c,
    }
}

pub fn calligraphic(c: char) -> char {
    match c {
        'B' => 'ℬ',
        'E' => 'ℰ',
        'F' => 'ℱ',
        'H' => 'ℋ',
        'I' => 'ℐ',
        'L' => 'ℒ',
        'M' => 'ℳ',
        'R' => 'ℛ',
        'A'..='Z' => char::from_u32(0x1D49C + (c as u32 - 'A' as u32)).unwrap_or(c),
        _ => c,
    }
}

pub fn fraktur(c: char) -> char {
    match c {
        'C' => 'ℭ',
        'H' => 'ℌ',
        'I' => 'ℑ',
        'R' => 'ℜ',
        'Z' => 'ℨ',
        'A'..='Z' => char::from_u32(0x1D504 + (c as u32 - 'A' as u32)).unwrap_or(c),
        'a'..='z' => char::from_u32(0x1D51E + (c as u32 - 'a' as u32)).unwrap_or(c),
        _ => c,
    }
}
